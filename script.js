let quizQuestions = [];
let currentQuestion = 0;
let score = 0;
let answered = false;

function startQuiz() {
    currentQuestion = 0;
    score = 0;
    answered = false;
    quizQuestions =
        [...questionPool]
        .sort(() => Math.random() - 0.5)
        .slice(0, 20);
    document
        .getElementById("quizCard")
        .classList.remove("hidden");
    document
        .getElementById("resultCard")
        .classList.add("hidden");
    showQuestion();
}

function showQuestion() {
    answered = false;
    const question =
        quizQuestions[currentQuestion];
    document
        .getElementById("progress")
        .textContent =
        `Question ${currentQuestion + 1} of 20`;
    document
        .getElementById("question")
        .textContent =
        question.question;
    const answersContainer =
        document.getElementById("answers");
    answersContainer.innerHTML = "";
    document
        .getElementById("feedback")
        .style.display = "none";
    document
        .getElementById("nextButton")
        .classList.add("hidden");
  
    let choices = [
        question.correct,
        ...question.wrong
    ];

    choices =
        choices.sort(
            () => Math.random() - 0.5
        );

  
    choices.forEach(choice => {
        const button =
            document.createElement("button");
        button.className =
            "answer";
        button.textContent =
            choice;
        button.onclick =
            () =>
            selectAnswer(
                button,
                choice
            );
        answersContainer
            .appendChild(button);
    });
}


function selectAnswer(
    button,
    selectedAnswer
) {

    if (answered) {
        return;
    }

    answered = true;
    const question =
        quizQuestions[currentQuestion];

    const allButtons =
        document.querySelectorAll(".answer");

    allButtons.forEach(button => {
        button.disabled = true;
    });

  
    if (
        selectedAnswer ===
        question.correct
    ) {
        button.classList.add(
            "correct"
        );
      
        score++;
        showFeedback(
            true,
            "Correct! ✓"
        );
    }


    else {
        button.classList.add(
            "wrong"
        );

        allButtons.forEach(button => {
            if (
                button.textContent ===
                question.correct
            ) {
                button.classList.add(
                    "correct"
                );
            }
        });

        showFeedback(
            false,
            `Incorrect. The correct answer is: ${question.correct}`
        );
    }
    document
        .getElementById("nextButton")
        .classList.remove("hidden");
}




function showFeedback(
    correct,
    message
) {
    const feedback =
        document.getElementById(
            "feedback"
        );
    feedback.textContent =
        message;
    feedback.style.display =
        "block";
    feedback.className =
        "feedback " +
        (
            correct
                ? "correct"
                : "wrong"
        );
}



document
    .getElementById("nextButton")
    .addEventListener(
        "click",
        () => {
            currentQuestion++;
            if (
                currentQuestion <
                quizQuestions.length
            ) {
                showQuestion();
            }
            else {
                showResults();
            }
        }
    );


function showResults() {
    document
        .getElementById("quizCard")
        .classList.add("hidden");
    document
        .getElementById("resultCard")
        .classList.remove("hidden");
    document
        .getElementById("finalScore")
        .textContent =
        `${score} / 20`;
    let message;
    if (score >= 12) {
        message =
            "You passed! You reached the 12/20 threshold!";
    }
    else {
        message =
            "Sorry, you did not pass... Keep practicing to reach at least 12/20!";
    }

    document
        .getElementById("resultMessage")
        .textContent =
        message;
}

